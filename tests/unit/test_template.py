"""The vendored template must reproduce the campaign's nine configs exactly.

The template used to live in a separate `setup-cctbx-pipeline` skill, outside
this repo. It was reconstructed here from the configs the
sfx-hutch-copilot-integration campaign rendered, so "did the reconstruction
lose anything?" is not a matter of opinion: re-render each iteration from its
recorded context and overrides, and diff against the file on disk.

That also turns what was an ad-hoc one-off check into a permanent regression
test, and removes the last runtime dependency on a skill outside this repo.

Skipped, not failed, when the campaign directory is unavailable -- these are
reference outputs on shared storage, not fixtures this repo owns.
"""

from __future__ import annotations

import difflib
import json
import pathlib
import re

import pytest

from hutch_tools import common as paths, lute, resolve as resolvers

CAMPAIGN = pathlib.Path(
    "/sdf/data/lcls/ds/prj/prjlute22/results/benchmarks/hutch_copilot/campaigns/"
    "sfx-hutch-copilot-integration"
)
PDB = pathlib.Path("/sdf/data/lcls/ds/mfx/mfx101624926/results/pam/1dpx.pdb")
LUTE_TEMPLATES = CAMPAIGN / "work/lute/config/templates"
TEMPLATE = paths.skill_root() / "templates" / "cctbx_pipeline.yaml.j2"

#: The campaign's rendered files credit skills that no longer exist. The
#: template now credits hutch-tools, so these two comment lines are normalised
#: before comparison. Every key and value is still compared strictly.
_ATTRIBUTION = (
    re.compile(r"^# Generated by .*$", re.M),
    re.compile(r"^(  # Versioned merge output \(iteration v\d+\)).*$", re.M),
)

#: Comment lines the vendored template adds which the campaign files do not have.
#: Comments only -- if one of these ever matched a key, the strict comparison of
#: every key and value below would still catch it.
_ADDED_COMMENTS = re.compile(
    r"^  # (?:Resolving `tag`|# away with|away with|NB: this note|directly above).*\n",
    re.M,
)

ITERATIONS = list(range(2, 11))


def _normalise(text: str) -> str:
    text = _ATTRIBUTION[0].sub("# Generated by X", text)
    text = _ATTRIBUTION[1].sub(r"\1", text)
    return _ADDED_COMMENTS.sub("", text)


def _context(n: int, spec: dict) -> dict:
    cell = resolvers.cell(str(PDB))["value"]
    return {
        "generator": "hutch-tools",
        "experiment": "mfx101624926",
        "tag": "Lyso",
        "work_dir": f"{CAMPAIGN}/work/iter{n:02d}",
        "pdb_file": str(PDB),
        "geometry_file": "/sdf/data/lcls/ds/mfx/mfx101624926/results/common/geom/refined.expt",
        "mask_file": ("/sdf/data/lcls/ds/mfx/mfx101624926/results/common/masks/"
                      "shift1_noisy_panels.mask"),
        "d_min": spec["d_min"],
        "detector_address": "jungfrau",
        "unit_cell": cell["unit_cell"],
        "space_group": cell["space_group"],
        "date": "2026/08/29",
        "merge_version": f"v{n:03d}",
    }


def _overrides(n: int, spec: dict) -> dict:
    # The campaign's Kerberos route-around, expressed as ordinary overrides.
    ovr = {
        "MergeCCTBXXFEL.phil_parameters.tag": lute.DELETE,
        "MergeCCTBXXFEL.phil_parameters.input_path": [
            f"{CAMPAIGN}/work/iter{n:02d}/r0036/scale"
        ],
    }
    ovr.update(spec["overrides"])
    return ovr


def _available() -> bool:
    return TEMPLATE.exists() and PDB.exists() and (CAMPAIGN / "params").is_dir()


pytestmark = pytest.mark.skipif(
    not _available(), reason="campaign reference outputs not available on this host"
)


@pytest.mark.parametrize("n", ITERATIONS)
def test_template_reproduces_the_campaign_config(n):
    spec = json.loads((CAMPAIGN / f"params/iter{n:02d}.json").read_text())
    expected_path = CAMPAIGN / f"pipeline/iter{n:02d}/mfx101624926_cctbx_iter{n:02d}.yaml"
    if not expected_path.exists():
        pytest.skip(f"no recorded config for iteration {n}")

    report = lute.build(
        template=TEMPLATE,
        context=_context(n, spec),
        overrides=_overrides(n, spec),
        whitelist_dir=LUTE_TEMPLATES if LUTE_TEMPLATES.is_dir() else None,
    )

    got = _normalise(report["text"])
    want = _normalise(expected_path.read_text())
    if got != want:
        diff = "".join(difflib.unified_diff(
            want.splitlines(True), got.splitlines(True),
            fromfile=f"campaign iter{n:02d}", tofile="vendored template", n=1))
        pytest.fail(f"iteration {n} differs:\n{diff}")


@pytest.mark.parametrize("n", ITERATIONS)
def test_kerberos_route_around_is_reported_as_a_deletion(n):
    """The `tag` key must exist in the template for the override to remove it.

    If the template simply omitted `tag`, the rendered text would match but the
    override would report `absent` -- and `hutch-lute kerberos` would no longer
    have anything to detect. Fidelity here is behavioural, not just textual.
    """
    spec = json.loads((CAMPAIGN / f"params/iter{n:02d}.json").read_text())
    report = lute.build(
        template=TEMPLATE, context=_context(n, spec),
        overrides=_overrides(n, spec), whitelist_dir=None,
    )
    assert report["overrides"]["MergeCCTBXXFEL.phil_parameters.tag"] == "deleted"


def test_untouched_template_would_need_kerberos():
    from hutch_tools.lute import needs_kerberos

    rendered = lute.render_template(TEMPLATE, _context(10, {"d_min": 2.2}))
    needed, why = needs_kerberos(rendered)
    assert needed is True and "eLog tag" in why


def test_unit_cell_comes_from_cryst1_verbatim():
    spec = {"d_min": 2.0, "overrides": {}}
    report = lute.build(template=TEMPLATE, context=_context(2, spec),
                          overrides={}, whitelist_dir=None)
    assert 'indexing_known_symmetry_unit_cell: "77.05 77.05 37.21 90.0 90.0 90.0"' in report["text"]
    assert 'indexing_known_symmetry_space_group: "P 43 21 2"' in report["text"]
